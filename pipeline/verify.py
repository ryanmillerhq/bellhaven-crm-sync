"""End-state verification: what changed in the CRM, whether it's internally consistent, and whether it converged.

    python -m pipeline verify [--write]   (--write also saves data/crm-snapshot-after/ and docs/end-state.md)
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from .config import REPO_ROOT, get_settings
from .crm import ReadOnlyCRM
from .match import find_operator_id, match
from .proposals import build_cases, decided_keys_from_cases
from .run import load_scrape

TRACKED = ["name", "parent_name", "billing_street", "billing_city", "billing_state", "billing_zip", "care_type",
           "status", "duplicate_of_account", "chow_current_account"]


def diff_accounts(before: list[dict], after: list[dict]) -> tuple[list[dict], list[dict]]:
    b = {a["account_id"]: a for a in before}
    created = [a for a in after if a["account_id"] not in b]
    changed = []
    for a in after:
        old = b.get(a["account_id"])
        if not old:
            continue
        fields = {f: (old.get(f), a.get(f)) for f in TRACKED if (old.get(f) or "") != (a.get(f) or "")}
        note_added = (a.get("note") or "") != (old.get("note") or "")
        if fields or note_added:
            changed.append({"account_id": a["account_id"], "name": a["name"], "fields": fields, "note_added": note_added})
    return created, changed


def invariants(accounts: list[dict]) -> list[str]:
    by = {a["account_id"]: a for a in accounts}
    problems = []
    for a in accounts:
        d, c = a.get("duplicate_of_account"), a.get("chow_current_account")
        if d:
            t = by.get(d)
            if a.get("status") != "Inactive":
                problems.append(f"{a['account_id']} {a['name']}: duplicate_of set but status is {a.get('status')}")
            if not t:
                problems.append(f"{a['account_id']} {a['name']}: duplicate_of points to missing {d}")
            elif t.get("duplicate_of_account") or t.get("status") == "Inactive":
                problems.append(f"{a['account_id']} {a['name']}: duplicate_of points to a settled/inactive record {d}")
        if c:
            t = by.get(c)
            if not t:
                problems.append(f"{a['account_id']} {a['name']}: chow_current_account points to missing {c}")
            elif t.get("status") != "Active":
                problems.append(f"{a['account_id']} {a['name']}: chow_current_account target {c} is {t.get('status')}")
    return problems


def verify(write: bool = False, scrape_file: str | None = None) -> dict:
    s = get_settings()
    crm = ReadOnlyCRM(s.crm_base_url, s.crm_api_token)
    accounts, contacts = crm.accounts(), crm.contacts()
    before = json.loads((REPO_ROOT / "data/crm-snapshot-before/accounts.json").read_text(encoding="utf-8"))
    created, changed = diff_accounts(before, accounts)

    scrape_path = scrape_file or sorted((REPO_ROOT / "data/scrapes").glob("*.json"))[-1]
    locations, _ = load_scrape(scrape_path)
    decided = []
    if s.database_url:
        from .store import Store
        st = Store(s.database_url)
        decided = st.decided_cases()
        st.close()
    remaining, results = build_cases(match(locations, accounts, contacts), "verify", True,
                                     decided=decided_keys_from_cases(decided))
    op_id = find_operator_id(accounts)
    children = [a for a in accounts if a.get("parent_id") == op_id]
    report = {
        "checked_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "accounts": len(accounts), "created": created, "changed": changed,
        "invariant_problems": invariants(accounts),
        "undecided_cases_remaining": [(c["title"], c["kind"]) for c in remaining],
        "in_sync": sum(1 for r in results if r["classification"] == "in_sync"),
        "decided_not_applied": sum(1 for r in results if r["classification"] == "decided"),
        "operator_children": {st: sum(1 for a in children if a.get("status") == st) for st in ("Active", "Needs Review", "Inactive")},
    }
    if write:
        out = REPO_ROOT / "data/crm-snapshot-after"
        out.mkdir(parents=True, exist_ok=True)
        (out / "accounts.json").write_text(json.dumps(accounts, indent=1) + "\n", encoding="utf-8")
        (out / "contacts.json").write_text(json.dumps(contacts, indent=1) + "\n", encoding="utf-8")
        _write_markdown(report, REPO_ROOT / "docs/end-state.md")
    return report


def _write_markdown(r: dict, path: Path) -> None:
    lines = ["# CRM end state", "",
             f"Checked {r['checked_at']} against the live CRM ({r['accounts']} accounts). Generated by "
             "`python -m pipeline verify --write`. Snapshots: [before](../data/crm-snapshot-before/) / "
             "[after](../data/crm-snapshot-after/).", "",
             f"- **Converged:** {len(r['undecided_cases_remaining'])} undecided cases remain; {r['in_sync']} communities in sync"
             f"{'; ' + str(r['decided_not_applied']) + ' with a change deliberately rejected' if r['decided_not_applied'] else ''}.",
             f"- **Consistency:** {len(r['invariant_problems'])} problems (duplicate and CHOW pointers all resolve to live records)."
             if not r["invariant_problems"] else f"- **Consistency problems:** {r['invariant_problems']}",
             f"- **Bellhaven children:** {r['operator_children']}", "",
             f"## Created ({len(r['created'])})", "", "| Account | Name | Parent | Address |", "|---|---|---|---|"]
    for a in r["created"]:
        lines.append(f"| {a['account_id']} | {a['name']} | {a.get('parent_name', '')} | {a.get('billing_street')}, "
                     f"{a.get('billing_city')} {a.get('billing_state')} {a.get('billing_zip')} |")
    lines += ["", f"## Changed ({len(r['changed'])})", "", "| Account | Name | Changes |", "|---|---|---|"]
    for c in r["changed"]:
        ch = "; ".join(f"{f}: “{o or '∅'}” → “{n or '∅'}”" for f, (o, n) in c["fields"].items())
        lines.append(f"| {c['account_id']} | {c['name']} | {ch}{' · note appended' if c['note_added'] else ''} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
